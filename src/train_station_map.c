static void Task_TrainMap(u8 taskId)
{
    u32 next, blocked;
    s32 dx = 0, dy = 0;

    switch (sMap->state)
    {
    case STATE_FADE_IN:
        if (!gPaletteFade.active)
            sMap->state = STATE_INPUT;
        break;
    case STATE_INPUT:
        if (JOY_NEW(B_BUTTON))
        {
            PlaySE(SE_SELECT);
            sMap->result = TRAIN_STATION_NONE;
            BeginNormalPaletteFade(PALETTES_ALL, 0, 0, 16, RGB_BLACK);
            sMap->state = STATE_FADE_OUT;
            break;
        }
        if (JOY_NEW(A_BUTTON))
        {
            if (!IsSelectable(sMap->cursor))
            {
                PlaySE(SE_FAILURE);
                break;
            }
            PlaySE(SE_SELECT);
            StringCopy(gStringVar1, GetTrainStation(sMap->cursor)->name);
            StringExpandPlaceholders(gStringVar4, sText_Confirm);
            sMap->msgWindowId = AddWindow(&sMessageWindowTemplate);
            FillWindowPixelBuffer(sMap->msgWindowId, PIXEL_FILL(1));
            PutWindowTilemap(sMap->msgWindowId);
            ClearWindowTilemap(WIN_HINT);
            DrawDialogFrameWithCustomTileAndPalette(sMap->msgWindowId, FALSE, TILE_MSGBOX, PAL_MSGBOX);
            AddTextPrinterParameterized(sMap->msgWindowId, FONT_NORMAL, gStringVar4, 0, 1, GetPlayerTextSpeedDelay(), NULL);
            CopyWindowToVram(sMap->msgWindowId, COPYWIN_FULL);
            ScheduleBgCopyTilemapToVram(0);
            sMap->state = STATE_CONFIRM_PRINT;
            break;
        }
        if (JOY_NEW(DPAD_LEFT))
            dx = -1;
        else if (JOY_NEW(DPAD_RIGHT))
            dx = 1;
        else if (JOY_NEW(DPAD_UP))
            dy = -1;
        else if (JOY_NEW(DPAD_DOWN))
            dy = 1;
        if (dx || dy)
        {
            next = FindStationInDirection(dx, dy, &blocked);
            if (next != TRAIN_STATION_NONE)
            {
                PlaySE(SE_DEX_SCROLL);
                SelectStation(next, FALSE);
            }
            else if (blocked != TRAIN_STATION_NONE)
            {
                PlaySE(SE_FAILURE);
                sMap->shakeTimer = SHAKE_FRAMES;
                sMap->blinkTimer = BLINK_FRAMES;
                sMap->blinkStation = blocked;
                ShowTrayMessage(GetTrainStationState(blocked) == TRAIN_STATION_STATE_CLOSED ? sText_Closed : sText_NotVisited);
                sMap->state = STATE_DENIED;
            }
        }
        break;
    case STATE_DENIED:
        if (JOY_NEW(A_BUTTON | B_BUTTON | DPAD_ANY))
        {
            CloseTrayMessage(FALSE);
            sMap->state = STATE_INPUT;
        }
        break;
    case STATE_CONFIRM_PRINT:
        if (!IsTextPrinterActiveOnWindow(sMap->msgWindowId))
        {
            CreateYesNoMenu(&sYesNoWindowTemplate, TILE_BORDER, PAL_BORDER, 0);
            sMap->state = STATE_CONFIRM_YESNO;
        }
        break;
    case STATE_CONFIRM_YESNO:
        switch (Menu_ProcessInputNoWrapClearOnChoose())
        {
        case 0: // YES
            sMap->result = sMap->cursor;
            BeginNormalPaletteFade(PALETTES_ALL, 0, 0, 16, RGB_BLACK);
            sMap->state = STATE_FADE_OUT;
            break;
        case 1: // NO
        case MENU_B_PRESSED:
            PlaySE(SE_SELECT);
            CloseTrayMessage(TRUE);
            sMap->state = STATE_INPUT;
            break;
        }
        break;
    case STATE_FADE_OUT:
        if (!gPaletteFade.active)
        {
            DestroyTask(taskId);
            ExitTrainMap();
        }
        break;
    }
}

