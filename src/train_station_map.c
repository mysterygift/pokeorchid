static void UpdateMapScroll(void)
{
    if (sMap->camTimer < CAM_PAN_FRAMES)
    {
        sMap->camTimer++;
        sMap->camX = EaseOutI(sMap->camFromX, sMap->camToX, sMap->camTimer, CAM_PAN_FRAMES);
        sMap->camY = EaseOutI(sMap->camFromY, sMap->camToY, sMap->camTimer, CAM_PAN_FRAMES);
    }
    if (sMap->ringTimer < RING_MOVE_FRAMES)
    {
        const struct TrainMapStation *st = &sTrainMapStations[sMap->cursor];
        sMap->ringTimer++;
        sMap->ringX = EaseOutI(sMap->ringFromX, st->x, sMap->ringTimer, RING_MOVE_FRAMES);
        sMap->ringY = EaseOutI(sMap->ringFromY, st->y, sMap->ringTimer, RING_MOVE_FRAMES);
    }
    sMap->frame++;
}

static inline s16 ScreenX(s32 canvasX)
{
    return canvasX - sMap->camX;
}

static inline s16 ScreenY(s32 canvasY)
{
    return canvasY - sMap->camY + MAP_STRIP_TOP;
}

static void PlaceSprite(u8 spriteId, s32 canvasX, s32 canvasY)
{
    struct Sprite *sprite = &gSprites[spriteId];
    s16 x = ScreenX(canvasX), y = ScreenY(canvasY);
    // Keep far-off sprites out of the 9-bit OAM wrap range.
    if (x < -32 || x > DISPLAY_WIDTH + 32 || y < -32 || y > DISPLAY_HEIGHT + 32)
    {
        sprite->x = DISPLAY_WIDTH + 64;
        sprite->y = DISPLAY_HEIGHT + 64;
    }
    else
    {
        sprite->x = x;
        sprite->y = y;
    }
}

static void UpdateMapSprites(void)
{
    u32 i;
    s32 shake = 0;

    for (i = 0; i < TRAIN_STATION_COUNT; i++)
        PlaceSprite(sMap->nodeSpriteIds[i], sTrainMapStations[i].x, sTrainMapStations[i].y);

    if (sMap->shakeTimer)
    {
        static const s8 sShake[SHAKE_FRAMES] = { 2, 2, 0, -2, -2, 0, 2, 2, 0, -2, -2, 0 };
        shake = sShake[SHAKE_FRAMES - sMap->shakeTimer];
        sMap->shakeTimer--;
    }
    PlaceSprite(sMap->ringSpriteId, sMap->ringX + shake, sMap->ringY);

    if (sMap->blinkTimer)
    {
        sMap->blinkTimer--;
        PlaceSprite(sMap->blinkSpriteId, sTrainMapStations[sMap->blinkStation].x, sTrainMapStations[sMap->blinkStation].y);
        gSprites[sMap->blinkSpriteId].invisible = ((BLINK_FRAMES - 1 - sMap->blinkTimer) / 4) & 1;
    }
    else
    {
        gSprites[sMap->blinkSpriteId].invisible = TRUE;
    }

    if (sMap->here != TRAIN_STATION_NONE)
        PlaceSprite(sMap->headSpriteId, sTrainMapStations[sMap->here].x, sTrainMapStations[sMap->here].y - 14);

    // Pill follows the ring's station label once the ring has arrived.
    for (i = 0; i < sMap->pillCount; i++)
    {
        PlaceSprite(sMap->pillSpriteIds[i], sMap->pillX[i] + 4, sMap->pillY + 8);
        gSprites[sMap->pillSpriteIds[i]].invisible = sMap->ringTimer < RING_MOVE_FRAMES;
    }

    UpdateChevrons();
}

static bool32 EdgeHasCell(const struct TrainMapEdge *edge, s32 col, s32 row)
{
    u32 c;
    if (col < 0 || row < 0 || col >= CANVAS_TILES_W || row >= TRAIN_MAP_CANVAS_H / 8)
        return FALSE;
    for (c = 0; c < edge->cellsCount; c++)
        if (sTrainMapEdgeCells[edge->cellsStart + c] == row * CANVAS_TILES_W + col)
            return TRUE;
    return FALSE;
}

// Red chevrons where a tube leaves the visible strip (IMPLEMENTATION.md "Chevrons"): for each edge
// and side, the edge's cells on the last visible column/row whose neighbour just outside is also
// on the edge; one chevron at the middle of them, at a fixed spot on that side of the viewport.
static void UpdateChevrons(void)
{
    u32 e, c, side, used = 0;
    s32 bob = (sMap->frame / 16) & 1;
    s32 c0 = sMap->camX / 8, c1 = (sMap->camX + VIEW_W - 1) / 8;
    s32 r0 = sMap->camY / 8, r1 = (sMap->camY + VIEW_H - 1) / 8;

    for (e = 0; e < TRAIN_MAP_EDGE_COUNT; e++)
    {
        const struct TrainMapEdge *edge = &sTrainMapEdges[e];
        for (side = 0; side < 4 && used < MAX_CHEVRONS; side++)
        {
            // side: 0 right, 1 left, 2 down, 3 up
            s32 lo = 0x7FFF, hi = -1;
            for (c = 0; c < edge->cellsCount; c++)
            {
                u32 cell = sTrainMapEdgeCells[edge->cellsStart + c];
                s32 col = cell % CANVAS_TILES_W, row = cell / CANVAS_TILES_W;
                s32 v;
                switch (side)
                {
                case 0: if (col != c1 || row < r0 || row > r1 || !EdgeHasCell(edge, col + 1, row)) continue; v = row; break;
                case 1: if (col != c0 || row < r0 || row > r1 || !EdgeHasCell(edge, col - 1, row)) continue; v = row; break;
                case 2: if (row != r1 || col < c0 || col > c1 || !EdgeHasCell(edge, col, row + 1)) continue; v = col; break;
                default: if (row != r0 || col < c0 || col > c1 || !EdgeHasCell(edge, col, row - 1)) continue; v = col; break;
                }
                if (v < lo) lo = v;
                if (v > hi) hi = v;
            }
            if (hi >= 0)
            {
                struct Sprite *chev = &gSprites[sMap->chevronSpriteIds[used++]];
                s32 mid = (lo + hi) / 2;
                s32 cx = mid * 8 + 4 - sMap->camX;
                s32 cy = mid * 8 + 4 - sMap->camY + MAP_STRIP_TOP;
                if (cx < 8) cx = 8;
                if (cx > 231) cx = 231;
                if (cy < 24) cy = 24;
                if (cy > 119) cy = 119;
                // Positions below are the 16x16 frame's top-left; sprites are centred, so +8.
                switch (side)
                {
                case 0: chev->x = 226 + bob + 8; chev->y = cy; break;
                case 1: chev->x = -2 - bob + 8;  chev->y = cy; break;
                case 2: chev->x = cx; chev->y = 113 + bob + 8; break;
                default: chev->x = cx; chev->y = 14 - bob + 8; break;
                }
                StartSpriteAnim(chev, side < 2 ? 0 : 1);
                chev->oam.matrixNum = (side == 1 ? ST_OAM_HFLIP : 0) | (side == 3 ? ST_OAM_VFLIP : 0);
                chev->invisible = FALSE;
            }
        }
    }
    for (; used < MAX_CHEVRONS; used++)
        gSprites[sMap->chevronSpriteIds[used]].invisible = TRUE;
}

