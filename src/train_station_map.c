static inline u32 CanvasCellToBufferIndex(u32 cell)
{
    u32 x = cell % CANVAS_TILES_W;
    u32 y = cell / CANVAS_TILES_W;
    return (x / 32) * 32 * 32 + y * 32 + (x % 32);
}

static void SetCellPalette(u32 cell, u32 pal)
{
    u16 *entry = &sMap->diagramMap[CanvasCellToBufferIndex(cell)];
    *entry = (*entry & 0x0FFF) | (pal << 12);
}

static void RestoreCellPalette(u32 cell)
{
    u32 i = CanvasCellToBufferIndex(cell);
    sMap->diagramMap[i] = sDiagram_Map[i];
}

static s32 EaseOutI(s32 from, s32 to, s32 t, s32 n)
{
    s32 r = n - t;
    return to - ((to - from) * r * r) / (n * n);
}

static s16 ClampCamX(s32 x)
{
    if (x < 0)
        return 0;
    if (x > TRAIN_MAP_CANVAS_W - VIEW_W)
        return TRAIN_MAP_CANVAS_W - VIEW_W;
    return x;
}

static s16 ClampCamY(s32 y)
{
    if (y < 0)
        return 0;
    if (y > TRAIN_MAP_CANVAS_H - VIEW_H)
        return TRAIN_MAP_CANVAS_H - VIEW_H;
    return y;
}

static bool32 StationsShareLine(u32 a, u32 b)
{
    return (sTrainMapStations[a].lineMask & sTrainMapStations[b].lineMask) != 0;
}

static bool32 IsSelectable(u32 station)
{
    return station != sMap->here && sMap->accessible[station];
}

