static void SelectStation(u8 station, bool32 instant)
{
    const struct TrainMapStation *st = &sTrainMapStations[station];
    s32 sx, sy;
    u32 i, w, n;

    sMap->cursor = station;

    // Ring travels from where it is now.
    sMap->ringFromX = sMap->ringX;
    sMap->ringFromY = sMap->ringY;
    if (instant)
    {
        sMap->ringX = sMap->ringFromX = st->x;
        sMap->ringY = sMap->ringFromY = st->y;
        sMap->ringTimer = RING_MOVE_FRAMES;
    }
    else
    {
        sMap->ringTimer = 0;
    }

    // Camera: hold while the station is inside the dead zone, otherwise re-centre on it.
    sx = st->x - sMap->camX;
    sy = st->y - sMap->camY;
    if (instant)
    {
        sMap->camX = sMap->camToX = ClampCamX(st->x - VIEW_W / 2);
        sMap->camY = sMap->camToY = ClampCamY(st->y - VIEW_H / 2);
        sMap->camTimer = CAM_PAN_FRAMES;
    }
    else if (sx < DEADZONE_LEFT || sx > DEADZONE_RIGHT || sy < DEADZONE_TOP || sy > DEADZONE_BOTTOM)
    {
        sMap->camFromX = sMap->camX;
        sMap->camFromY = sMap->camY;
        sMap->camToX = ClampCamX(st->x - VIEW_W / 2);
        sMap->camToY = ClampCamY(st->y - VIEW_H / 2);
        sMap->camTimer = 0;
    }

    // Gold pill behind the label: left cap, middles, right cap (8x16 each).
    (void)w;
    n = st->labelW / 8;
    if (n < 2)
        n = 2;
    if (n > MAX_PILL_PIECES)
        n = MAX_PILL_PIECES;
    for (i = 0; i < MAX_PILL_PIECES; i++)
    {
        struct Sprite *piece = &gSprites[sMap->pillSpriteIds[i]];
        if (i < n)
        {
            sMap->pillX[i] = st->labelX + i * 8;
            StartSpriteAnim(piece, i == 0 ? 0 : (i == n - 1 ? 2 : 1));
            piece->invisible = FALSE;
        }
        else
        {
            piece->invisible = TRUE;
        }
    }
    sMap->pillCount = n;
    sMap->pillY = st->labelY;

    RefreshDiagramPalettes();
    PrintTray();
}

static void PrintTray(void)
{
    const struct TrainMapStation *st = &sTrainMapStations[sMap->cursor];
    const struct TrainStation *station = GetTrainStation(sMap->cursor);
    u8 *str = gStringVar4;
    u32 i, lines = 0;

    FillWindowPixelBuffer(WIN_NAME, PIXEL_FILL(0));
    AddTextPrinterParameterized3(WIN_NAME, FONT_NORMAL, 2, 1, sTextColor_Name, TEXT_SKIP_DRAW, station->name);
    CopyWindowToVram(WIN_NAME, COPYWIN_GFX);

    *str = EOS;
    for (i = 0; i < TRAIN_MAP_LINE_COUNT; i++)
    {
        if (!(st->lineMask & (1 << i)))
            continue;
        if (lines++)
            StringAppend(str, sText_Plus);
        StringAppend(str, sTrainMapLineNames[i]);
    }
    StringAppend(str, lines > 1 ? sText_Lines : sText_Line);
    FillWindowPixelBuffer(WIN_LINE, PIXEL_FILL(0));
    AddTextPrinterParameterized3(WIN_LINE, FONT_SMALL, 2, 0, sTextColor_Line, TEXT_SKIP_DRAW, str);
    CopyWindowToVram(WIN_LINE, COPYWIN_GFX);

    // Tray pictogram: the station's line, or the interchange frame.
    if (st->interchange)
        StartSpriteAnim(&gSprites[sMap->trayLineSpriteId], TRAIN_MAP_LINE_COUNT);
    else
        for (i = 0; i < TRAIN_MAP_LINE_COUNT; i++)
            if (st->lineMask & (1 << i))
            {
                StartSpriteAnim(&gSprites[sMap->trayLineSpriteId], i);
                break;
            }
}

// Cone rule (IMPLEMENTATION.md): candidates inside a 90-degree cone in the pressed direction,
// score = along + |across| (+64 if no shared line), lowest wins, ties to the lower id.
// If nothing selectable, *blocked = lowest-scoring unselectable station in the cone.
static u32 FindStationInDirection(s32 dirX, s32 dirY, u32 *blocked)
{
    const struct TrainMapStation *from = &sTrainMapStations[sMap->cursor];
    u32 i, best = TRAIN_STATION_NONE, bestScore = 0xFFFFFFFF, blockedScore = 0xFFFFFFFF;

    *blocked = TRAIN_STATION_NONE;
    for (i = 0; i < TRAIN_STATION_COUNT; i++)
    {
        s32 dx, dy, along, across;
        u32 score;

        if (i == sMap->cursor || i == sMap->here)
            continue;
        dx = sTrainMapStations[i].x - from->x;
        dy = sTrainMapStations[i].y - from->y;
        if (dirX)
        {
            along = dx * dirX;
            across = dy;
        }
        else
        {
            along = dy * dirY;
            across = dx;
        }
        if (across < 0)
            across = -across;
        if (along <= 0 || across > along)
            continue;

        score = along + across + (StationsShareLine(i, sMap->cursor) ? 0 : 64);
        if (IsSelectable(i))
        {
            if (score < bestScore)
            {
                best = i;
                bestScore = score;
            }
        }
        else if (score < blockedScore)
        {
            *blocked = i;
            blockedScore = score;
        }
    }
    return best;
}

