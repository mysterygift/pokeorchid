static bool32 ODex_ListHasSpecies(const struct WildPokemonInfo *info, u32 count, enum Species species)
{
    u32 i;

    if (info == NULL)
        return FALSE;
    for (i = 0; i < count; i++)
    {
        if (info->wildPokemon[i].species == species)
            return TRUE;
    }
    return FALSE;
}

#define ODEX_AREA_LINES 3

static void ODex_PrintAreaTab(enum Species species)
{
    mapsec_u16_t found[ODEX_AREA_LINES + 1];
    u8 method[ODEX_AREA_LINES + 1];
    u32 numFound = 0, i, j, t, m;
    u8 str[64];
    u8 *end;

    // the region map would go on BG2; Tosa has no map art yet, so the well says so
    ODex_PrintCentered(WIN_INFO, FONT_NORMAL, sODexText_MapTitle, ODEX_AREA_X0, ODEX_AREA_X1 - ODEX_AREA_X0 + 1,
                       (ODEX_AREA_Y0 + ODEX_AREA_Y1) / 2 - 16, sODexText_Faint);
    ODex_PrintCentered(WIN_INFO, FONT_NARROW, sODexText_MapNone, ODEX_AREA_X0, ODEX_AREA_X1 - ODEX_AREA_X0 + 1,
                       (ODEX_AREA_Y0 + ODEX_AREA_Y1) / 2 - 2, sODexText_Faint);

    for (i = 0; gWildMonHeaders[i].mapGroup != MAP_GROUP(MAP_UNDEFINED) && numFound <= ODEX_AREA_LINES; i++)
    {
        mapsec_u16_t mapsec = Overworld_GetMapHeaderByGroupAndId(gWildMonHeaders[i].mapGroup, gWildMonHeaders[i].mapNum)->regionMapSectionId;

        for (t = 0; t < TIMES_OF_DAY_COUNT; t++)
        {
            const struct WildEncounterTypes *enc = &gWildMonHeaders[i].encounterTypes[t];

            if (ODex_ListHasSpecies(enc->landMonsInfo, NUM_LAND_MONS_ENCOUNTER_SLOTS, species))
                m = 0;
            else if (ODex_ListHasSpecies(enc->waterMonsInfo, NUM_WATER_MONS_ENCOUNTER_SLOTS, species))
                m = 1;
            else if (ODex_ListHasSpecies(enc->rockSmashMonsInfo, NUM_ROCK_SMASH_MONS_ENCOUNTER_SLOTS, species))
                m = 2;
            else if (ODex_ListHasSpecies(enc->fishingMonsInfo, NUM_FISHING_MONS_ENCOUNTER_SLOTS, species))
                m = 3;
            else
                continue;

            for (j = 0; j < numFound; j++)
            {
                if (found[j] == mapsec)
                    break;
            }
            if (j == numFound)
            {
                found[numFound] = mapsec;
                method[numFound] = m;
                numFound++;
            }
            break;
        }
    }

    StringCopy(gStringVar1, GetSpeciesName(species));
    if (numFound == 0)
    {
        ODex_Print(WIN_INFO, FONT_NORMAL, sODexText_AreaUnknown, ODEX_DESC_X, ODEX_DESC_Y, sODexText_Ink);
        return;
    }
    StringExpandPlaceholders(str, sODexText_LivesIn);
    ODex_Print(WIN_INFO, FONT_NORMAL, str, ODEX_DESC_X, ODEX_DESC_Y, sODexText_Ink);
    for (j = 0; j < numFound && j < ODEX_AREA_LINES; j++)
    {
        if (j == ODEX_AREA_LINES - 1 && numFound > ODEX_AREA_LINES)
        {
            ODex_Print(WIN_INFO, FONT_NORMAL, sODexText_AndMore, ODEX_DESC_X, ODEX_DESC_Y + (j + 1) * ODEX_DESC_PITCH, sODexText_Ink);
            break;
        }
        end = GetMapName(str, found[j], 0);
        *end++ = CHAR_SPACE;
        *end++ = CHAR_LEFT_PAREN;
        end = StringCopy(end, sODexEncounterNames[method[j]]);
        *end++ = CHAR_RIGHT_PAREN;
        *end = EOS;
        ODex_Print(WIN_INFO, GetFontIdToFit(str, FONT_NORMAL, 0, DISPLAY_WIDTH - 2 * ODEX_DESC_X), str,
                   ODEX_DESC_X, ODEX_DESC_Y + (j + 1) * ODEX_DESC_PITCH, sODexText_Ink);
    }
}

