static void Task_ODexLoadSearch(u8 taskId)
{
    s16 *data = gTasks[taskId].data;

    switch (tSearchState)
    {
    case 0:
        if (gPaletteFade.active)
            return;
        sPokedexView->currentPage = PAGE_SEARCH;
        ODex_DestroyListSprites();
        ResetOtherVideoRegisters(0);
        ResetBgsAndClearDma3BusyFlags(0);
        InitBgsFromTemplates(0, sODexSearch_BgTemplate, ARRAY_COUNT(sODexSearch_BgTemplate));
        SetBgTilemapBuffer(3, AllocZeroed(BG_SCREEN_SIZE));
        SetBgTilemapBuffer(2, AllocZeroed(BG_SCREEN_SIZE));
        SetBgTilemapBuffer(1, AllocZeroed(BG_SCREEN_SIZE));
        InitWindows(sODexSearch_WindowTemplates);
        DeactivateAllTextPrinters();
        PutWindowTilemap(0);
        CopyBgTilemapBufferToVram(2);
        DecompressAndLoadBgGfxUsingHeap(3, gOrchidDexEntry_Gfx, ODEX_ENTRY_NUM_TILES * TILE_SIZE_4BPP, 0, 0);
        ODex_FillGridMap(1);
        LoadPalette(gOrchidDexScreen_Pal, BG_PLTT_ID(0), 3 * PLTT_SIZE_4BPP);
        tSearchState++;
        break;
    case 1:
        ResetSpriteData();
        FreeAllSpritePalettes();
        gReservedSpritePaletteCount = 8;
        sPokedexView->odexTypeSpriteIds[0] = sPokedexView->odexTypeSpriteIds[1] = SPRITE_NONE;
        sPokedexView->odexArrowSpriteIds[0] = sPokedexView->odexArrowSpriteIds[1] = SPRITE_NONE;
        ODex_LoadSpriteGfx();
        ODex_CreateTypeIcons();
        ODex_CreateArrows(0, 0, 0);
        tSearchType1Spr = sPokedexView->odexTypeSpriteIds[0];
        tSearchType2Spr = sPokedexView->odexTypeSpriteIds[1];
        tSearchArrowL = sPokedexView->odexArrowSpriteIds[0];
        tSearchArrowR = sPokedexView->odexArrowSpriteIds[1];
        tSearchRow = ODEX_SROW_ORDER;
        tSearchOrder = sPokedexView->dexOrder;
        tSearchName = 0;
        tSearchType1 = tSearchType2 = 0;
        tSearchSlot = 0;
        tSearchMode = IsNationalPokedexEnabled() ? sPokedexView->dexMode : DEX_MODE_HOENN;
        ODex_SearchHighlight(tSearchRow);
        ODex_SearchPrint(taskId);
        tSearchState++;
        break;
    case 2:
        SetGpuReg(REG_OFFSET_DISPCNT, DISPCNT_MODE_0 | DISPCNT_OBJ_1D_MAP | DISPCNT_OBJ_ON);
        ShowBg(1);
        ShowBg(2);
        ShowBg(3);
        BeginNormalPaletteFade(PALETTES_ALL, 0, 16, 0, RGB_BLACK);
        tSearchState++;
        break;
    case 3:
        if (!gPaletteFade.active)
        {
            tSearchState = 0;
            gTasks[taskId].func = Task_ODexSearchInput;
        }
        break;
    }
}

static s16 ODex_Cycle(s16 value, s32 delta, s32 count)
{
    value += delta;
    if (value < 0)
        value = count - 1;
    if (value >= count)
        value = 0;
    return value;
}

static void Task_ODexSearchInput(u8 taskId)
{
    s16 *data = gTasks[taskId].data;
    s32 delta = 0;
    u32 row = tSearchRow;

    if (JOY_NEW(B_BUTTON))
    {
        PlaySE(SE_PC_OFF);
        sPokedexView->screenSwitchState = 0;
        gTasks[taskId].func = Task_ODexSearchExit;
        return;
    }
    if (JOY_NEW(A_BUTTON))
    {
        if (row == ODEX_SROW_CANCEL)
        {
            PlaySE(SE_PC_OFF);
            sPokedexView->screenSwitchState = 0;
            gTasks[taskId].func = Task_ODexSearchExit;
        }
        else if (row == ODEX_SROW_SEARCH)
        {
            u8 mode = IsNationalPokedexEnabled() ? tSearchMode : DEX_MODE_HOENN;
            if (tSearchName == 0 && tSearchType1 == 0 && tSearchType2 == 0)
            {
                // No filter: re-sort / switch the main list (vanilla "SHIFT")
                sLastSelectedPokemon = 0;
                sODexLastTop = 0;
                sPokedexView->selectedPokemonBackup = 0;
                gSaveBlock2Ptr->pokedex.mode = mode;
                sPokedexView->dexModeBackup = mode;
                gSaveBlock2Ptr->pokedex.order = tSearchOrder;
                sPokedexView->dexOrderBackup = tSearchOrder;
                sPokedexView->screenSwitchState = 0;
                PlaySE(SE_PC_OFF);
                gTasks[taskId].func = Task_ODexSearchExit;
            }
            else
            {
                ODex_SearchHint(sODexText_Searching);
                DoPokedexSearch(mode, tSearchOrder, tSearchName ? tSearchName : 0xFF, 0xFF,
                                sDexSearchTypeIds[tSearchType1], sDexSearchTypeIds[tSearchType2]);
                if (sPokedexView->pokemonListCount != 0)
                {
                    PlaySE(SE_SUCCESS);
                    sPokedexView->screenSwitchState = 1;
                    sPokedexView->dexMode = mode;
                    sPokedexView->dexOrder = tSearchOrder;
                    gTasks[taskId].func = Task_ODexSearchExit;
                }
                else
                {
                    PlaySE(SE_FAILURE);
                    ODex_SearchHint(sText_NoMatchingPkmnWereFound);
                }
            }
        }
        else if (row == ODEX_SROW_TYPE)
        {
            tSearchSlot ^= 1;
            PlaySE(SE_SELECT);
            ODex_SearchPrint(taskId);
        }
        return;
    }

    if (JOY_NEW(DPAD_UP))
    {
        row = (row >= ODEX_SROW_SEARCH) ? ODEX_SROW_MODE : (row > 0 ? row - 1 : row);
    }
    else if (JOY_NEW(DPAD_DOWN))
    {
        row = (row < ODEX_SROW_MODE) ? row + 1 : (row == ODEX_SROW_MODE ? ODEX_SROW_SEARCH : row);
    }
    else if (JOY_REPEAT(DPAD_LEFT))
    {
        if (row == ODEX_SROW_CANCEL)
            row = ODEX_SROW_SEARCH;
        else
            delta = -1;
    }
    else if (JOY_REPEAT(DPAD_RIGHT))
    {
        if (row == ODEX_SROW_SEARCH)
            row = ODEX_SROW_CANCEL;
        else
            delta = 1;
    }

    if (row != tSearchRow)
    {
        tSearchRow = row;
        PlaySE(SE_SELECT);
        ODex_SearchHighlight(row);
        ODex_SearchPrint(taskId);
        return;
    }
    if (delta == 0 || row > ODEX_SROW_MODE)
        return;
    switch (row)
    {
    case ODEX_SROW_ORDER:
        tSearchOrder = ODex_Cycle(tSearchOrder, delta, ARRAY_COUNT(sODexOrderNames));
        break;
    case ODEX_SROW_NAME:
        tSearchName = ODex_Cycle(tSearchName, delta, NAME_YZ + 1);
        break;
    case ODEX_SROW_TYPE:
        if (tSearchSlot == 0)
            tSearchType1 = ODex_Cycle(tSearchType1, delta, ARRAY_COUNT(sDexSearchTypeIds));
        else
            tSearchType2 = ODex_Cycle(tSearchType2, delta, ARRAY_COUNT(sDexSearchTypeIds));
        break;
    case ODEX_SROW_MODE:
        if (!IsNationalPokedexEnabled())
        {
            PlaySE(SE_FAILURE);
            return;
        }
        tSearchMode = (tSearchMode == DEX_MODE_HOENN) ? DEX_MODE_NATIONAL : DEX_MODE_HOENN;
        break;
    }
    PlaySE(SE_SELECT);
    ODex_SearchPrint(taskId);
}

static void Task_ODexSearchExit(u8 taskId)
{
    s16 *data = gTasks[taskId].data;

    if (tSearchState == 0)
    {
        BeginNormalPaletteFade(PALETTES_ALL, 0, 0, 16, RGB_BLACK);
        tSearchState++;
    }
    else if (!gPaletteFade.active)
    {
        sODexGridBg = 0;
        FreeAllWindowBuffers();
        Free(GetBgTilemapBuffer(1));
        Free(GetBgTilemapBuffer(2));
        Free(GetBgTilemapBuffer(3));
        SetBgTilemapBuffer(1, NULL);
        SetBgTilemapBuffer(2, NULL);
        SetBgTilemapBuffer(3, NULL);
        DestroyTask(taskId);
    }
}

