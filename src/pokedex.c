// Gold palette on the selected search row / button
static void ODex_SearchHighlight(u32 row)
{
    u32 i;

    CopyToBgTilemapBuffer(3, gOrchidDexSearch_Tilemap, 0, 0);
    for (i = 0; i < 4; i++)
    {
        if (i == row)
            ODex_SetCellPalette(3, ODEX_S_X / 8, ODex_SearchRowY(i) / 8, (ODEX_S_W + 7) / 8, (ODex_SearchRowY(i) + 13) / 8 - ODex_SearchRowY(i) / 8 + 1, ODEX_PAL_SELECTED);
    }
    if (row == ODEX_SROW_SEARCH || row == ODEX_SROW_CANCEL)
    {
        u32 x = (row == ODEX_SROW_SEARCH) ? ODEX_S_BTN_X0 : ODEX_S_BTN_X1;
        ODex_SetCellPalette(3, x / 8, ODEX_S_BTN_Y / 8, ODEX_S_BTN_W / 8, (ODEX_S_BTN_Y + 17) / 8 - ODEX_S_BTN_Y / 8 + 1, ODEX_PAL_SELECTED);
    }
    CopyBgTilemapBufferToVram(3);
}

// TYPE row: two fixed recessed sockets (BG art) so the row always reads as two fields.
// A set slot shows its type icon centred in the socket; an unset slot shows "ANY" (INK_SOFT).
static s32 ODex_SocketX(u32 k)
{
    return ODEX_S_SOCKET_X0 + k * ODEX_S_SOCKET_PITCH;
}

static void ODex_SearchUpdateSprites(u8 taskId)
{
    s16 *data = gTasks[taskId].data;
    u32 row = tSearchRow;
    s32 y, lx, rx;
    u8 spr[2] = {tSearchType1Spr, tSearchType2Spr};
    s16 typeIdx[2] = {tSearchType1, tSearchType2};
    u32 i;

    for (i = 0; i < 2; i++)
    {
        struct Sprite *sprite = &gSprites[spr[i]];
        enum Type type = sDexSearchTypeIds[typeIdx[i]];

        if (type == TYPE_NONE)
        {
            sprite->invisible = TRUE;
            continue;
        }
        StartSpriteAnim(sprite, type);
        sprite->oam.paletteNum = gTypesInfo[type].palette;
        sprite->x = ODex_SocketX(i) + 2 + 16;
        sprite->y = ODEX_S_SOCKET_Y + 8;
        sprite->invisible = FALSE;
    }

    if (row > ODEX_SROW_MODE)
    {
        gSprites[tSearchArrowL].invisible = gSprites[tSearchArrowR].invisible = TRUE;
        return;
    }
    y = ODex_SearchRowY(row) + 7 + 1;
    lx = ODEX_S_X + ODEX_S_CAP + 12;
    rx = ODEX_S_X + ODEX_S_W - 12;
    if (row == ODEX_SROW_TYPE)
    {
        // chevrons flank the socket being edited, 3px clear on both sides
        lx = ODex_SocketX(tSearchSlot) - 6;
        rx = ODex_SocketX(tSearchSlot) + ODEX_S_SOCKET_W + 6;
    }
    gSprites[tSearchArrowL].x = lx;
    gSprites[tSearchArrowR].x = rx;
    gSprites[tSearchArrowL].y = gSprites[tSearchArrowR].y = y;
    gSprites[tSearchArrowL].invisible = gSprites[tSearchArrowR].invisible = FALSE;
}

static void ODex_SearchPrint(u8 taskId)
{
    s16 *data = gTasks[taskId].data;
    u32 i, y;
    const u8 *val;
    u8 str[8];

    FillWindowPixelBuffer(0, PIXEL_FILL(0));
    ODex_PrintCentered(0, FONT_NORMAL, sODexText_Search, 0, DISPLAY_WIDTH, 0, sODexText_Label);
    for (i = 0; i < 4; i++)
    {
        y = ODex_SearchRowY(i) - 1;
        ODex_PrintCentered(0, FONT_NORMAL, sODexSearchLabels[i], ODEX_S_X + 1, ODEX_S_CAP, y, sODexText_Label);
        val = NULL;
        switch (i)
        {
        case ODEX_SROW_ORDER:
            val = sODexOrderNames[tSearchOrder];
            break;
        case ODEX_SROW_NAME:
            val = tSearchName ? sDexSearchNameOptions[tSearchName].title : sODexText_Any;
            break;
        case ODEX_SROW_TYPE:
            if (tSearchType1 == 0)
                ODex_PrintCentered(0, FONT_NARROW, sODexText_AnyCaps, ODex_SocketX(0), ODEX_S_SOCKET_W, ODEX_S_SOCKET_Y, sODexText_Faint);
            if (tSearchType2 == 0)
                ODex_PrintCentered(0, FONT_NARROW, sODexText_AnyCaps, ODex_SocketX(1), ODEX_S_SOCKET_W, ODEX_S_SOCKET_Y, sODexText_Faint);
            break;
        case ODEX_SROW_MODE:
            val = tSearchMode == DEX_MODE_NATIONAL ? sODexText_National : sODexText_Tosa;
            break;
        }
        if (val)
            ODex_PrintCentered(0, FONT_NORMAL, val, ODEX_S_X + ODEX_S_CAP, ODEX_S_W - ODEX_S_CAP, y, sODexText_Ink);
    }
    ODex_PrintCentered(0, FONT_NORMAL, sODexText_Search, ODEX_S_BTN_X0, ODEX_S_BTN_W, ODEX_S_BTN_Y + 1, sODexText_Ink);
    ODex_PrintCentered(0, FONT_NORMAL, sODexText_Cancel, ODEX_S_BTN_X1, ODEX_S_BTN_W, ODEX_S_BTN_Y + 1, sODexText_Ink);
    (void)str;
    ODex_Print(0, FONT_NORMAL, sODexSearchHints[tSearchRow], ODEX_DESC_X, ODEX_S_TRAY_Y + 2, sODexText_Ink);
    CopyWindowToVram(0, COPYWIN_GFX);
    ODex_SearchUpdateSprites(taskId);
}

