// A on the list: the gold row flashes, BG0/2/3 darken (the grid and OBJ stay lit) while the pic
// glides from the list dais to the entry dais, then the entry page loads and brightens in.
static void Task_ODexOpenEntry(u8 taskId)
{
    u32 t = sPokedexView->odexTimer++;
    struct Sprite *pic = &gSprites[sPokedexView->odexPicSpriteId];

    if (t < ODEX_FLASH_FRAMES)
    {
        // Flash: the gold pill's face goes to SELECT_LIGHT
        u16 color = gOrchidDexScreen_Pal[16 + (t < ODEX_FLASH_FRAMES / 2 ? ODEX_C_SELECT_LIGHT : ODEX_C_SELECT)];
        LoadPalette(&color, BG_PLTT_ID(ODEX_PAL_SELECTED) + ODEX_C_SELECT, PLTT_SIZEOF(1));
        return;
    }
    if (t == ODEX_FLASH_FRAMES)
    {
        LoadPalette(&gOrchidDexScreen_Pal[16 + ODEX_C_SELECT], BG_PLTT_ID(ODEX_PAL_SELECTED) + ODEX_C_SELECT, PLTT_SIZEOF(1));
        ODex_SetListUiVisible(FALSE);
        SetGpuReg(REG_OFFSET_BLDCNT, ODEX_BLD_TARGETS);
    }
    t = t - ODEX_FLASH_FRAMES + 1;
    if (t <= ODEX_FADE_FRAMES)
    {
        s32 e = ODex_Ease(t);
        SetGpuReg(REG_OFFSET_BLDY, t * 16 / ODEX_FADE_FRAMES);
        pic->x = gTasks[taskId].tPicFromX + (ODEX_E_DAIS_X - gTasks[taskId].tPicFromX) * e / 256;
        pic->y = gTasks[taskId].tPicFromY + (gTasks[taskId].tPicToY - gTasks[taskId].tPicFromY) * e / 256;
        return;
    }

    // Swap screens: keep the pic, drop the other list sprites
    sODexLastTop = sPokedexView->odexTop;
    ODex_DestroyUiSprites();
    FreeWindowAndBgBuffers();
    sPokedexView->odexTab = ODEX_TAB_INFO;
    sPokedexView->currentPageBackup = sPokedexView->currentPage;
    gTasks[taskId].tLoadScreenTaskId = LoadInfoScreen(&sPokedexView->pokedexList[sPokedexView->selectedPokemon], sPokedexView->odexPicSpriteId);
    gTasks[taskId].func = sPokedexView->isSearchResults ? Task_WaitForExitSearchResultsInfoScreen : Task_WaitForExitInfoScreen;
}

