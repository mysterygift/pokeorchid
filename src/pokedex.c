// Dex number as shown in the current mode (regional in TOSA mode)
static void ODex_FormatNumber(u8 *dst, u16 dexNum)
{
    u32 num = dexNum;

    if (sPokedexView->dexMode == DEX_MODE_HOENN)
        num = NationalToRegionalOrder(dexNum);
    ConvertIntToDecimalStringN(dst, num, STR_CONV_MODE_LEADING_ZEROS, num > 999 ? 4 : 3);
}

