// For loading the main list or the search results
static bool8 ODex_LoadListPage(u8 page)
{
    switch (gMain.state)
    {
    case 0:
    default:
        if (gPaletteFade.active)
            return FALSE;
        sPokedexView->currentPage = page;
        sPokedexView->isSearchResults = (page != PAGE_MAIN);
        // Keep the sprites (the pic glides back from the entry page) and the grid running
        ResetOtherVideoRegisters(DISPCNT_OBJ_ON | DISPCNT_BG1_ON);
        ResetBgsAndClearDma3BusyFlags(0);
        InitBgsFromTemplates(0, sODexList_BgTemplate, ARRAY_COUNT(sODexList_BgTemplate));
        SetBgTilemapBuffer(3, AllocZeroed(BG_SCREEN_SIZE));
        SetBgTilemapBuffer(2, AllocZeroed(BG_SCREEN_SIZE));
        SetBgTilemapBuffer(1, AllocZeroed(BG_SCREEN_SIZE));
        SetBgTilemapBuffer(0, AllocZeroed(BG_SCREEN_SIZE));
        if (sPokedexView->odexFromEntry)
        {
            // Darkened: brightens in once the page is ready
            SetGpuReg(REG_OFFSET_BLDCNT, ODEX_BLD_TARGETS);
            SetGpuReg(REG_OFFSET_BLDY, 16);
        }
        else
        {
            ResetPaletteFade();
            SetGpuReg(REG_OFFSET_BLDCNT, 0);
            SetGpuReg(REG_OFFSET_BLDY, 0);
        }
        DecompressAndLoadBgGfxUsingHeap(3, gOrchidDexList_Gfx, ODEX_LIST_NUM_TILES * TILE_SIZE_4BPP, 0, 0);
        CopyToBgTilemapBuffer(3, gOrchidDexList_Tilemap, 0, 0);
        ODex_FillGridMap(1);
        ShowBg(1);
        LoadPalette(gOrchidDexScreen_Pal, BG_PLTT_ID(0), 3 * PLTT_SIZE_4BPP);
        InitWindows(sODexList_WindowTemplates);
        DeactivateAllTextPrinters();
        PutWindowTilemap(ODEX_LWIN_LIST);
        PutWindowTilemap(ODEX_LWIN_COUNTS);
        PutWindowTilemap(ODEX_LWIN_TITLE);
        if (page == PAGE_MAIN)
            CreatePokedexList(sPokedexView->dexMode, sPokedexView->dexOrder);
        gMain.state = 1;
        break;
    case 1:
        // The heavy part (text) first, while the carried pic is still up
        if (sPokedexView->selectedPokemon >= sPokedexView->pokemonListCount)
            sPokedexView->selectedPokemon = sPokedexView->pokemonListCount ? sPokedexView->pokemonListCount - 1 : 0;
        sPokedexView->odexTop = ODex_TopFor(sPokedexView->selectedPokemon, sPokedexView->isSearchResults ? 0 : sODexLastTop);
        sPokedexView->odexThumbSpriteId = SPRITE_NONE;
        ODex_PrintListHeader();
        ODex_RedrawList();
        CopyBgTilemapBufferToVram(0);
        CopyBgTilemapBufferToVram(3);
        gMain.state++;
        break;
    case 2:
        // Rebuild the sprites in one short frame so the carried pic never blinks
        ODex_DestroyPic();
        ResetSpriteData();
        FreeAllSpritePalettes();
        gReservedSpritePaletteCount = 8;
        sPokedexView->odexTypeSpriteIds[0] = sPokedexView->odexTypeSpriteIds[1] = SPRITE_NONE;
        sPokedexView->odexArrowSpriteIds[0] = sPokedexView->odexArrowSpriteIds[1] = SPRITE_NONE;
        ODex_LoadSpriteGfx();
        ODex_CreateTypeIcons();
        if (ODex_CanSwitchMode())
            ODex_CreateArrows(ODEX_HDR_ARROW_L_X, ODEX_HDR_ARROW_R_X, ODEX_HDR_ARROW_Y);
        if (sPokedexView->pokemonListCount > ODEX_LIST_ROWS)
            sPokedexView->odexThumbSpriteId = CreateSprite(&sODexThumbTemplate, ODEX_THUMB_X, ODEX_THUMB_TOP + 8, 0);
        ODex_SetListScroll(sPokedexView->odexScrollPx);
        ODex_ShowListSelection(FALSE);
        if (sPokedexView->odexFromEntry)
            ODex_SetListUiVisible(FALSE);
        gMain.state++;
        break;
    case 3:
        SetGpuReg(REG_OFFSET_DISPCNT, DISPCNT_MODE_0 | DISPCNT_OBJ_1D_MAP | DISPCNT_OBJ_ON);
        ShowBg(0);
        ShowBg(1);
        ShowBg(2);
        ShowBg(3);
        SetVBlankCallback(VBlankCB_Pokedex);
        if (sPokedexView->odexFromEntry)
            sPokedexView->odexTimer = ODEX_FADE_FRAMES;
        else
            BeginNormalPaletteFade(PALETTES_ALL, 0, 16, 0, RGB_BLACK);
        gMain.state++;
        break;
    case 4:
        ODex_UpdatePicSlide();
        if (sPokedexView->odexTimer)
        {
            sPokedexView->odexTimer--;
            SetGpuReg(REG_OFFSET_BLDY, sPokedexView->odexTimer * 16 / ODEX_FADE_FRAMES);
            break;
        }
        if (!gPaletteFade.active)
        {
            SetGpuReg(REG_OFFSET_BLDCNT, 0);
            if (sPokedexView->odexFromEntry)
                ODex_SetListUiVisible(TRUE);
            sPokedexView->odexFromEntry = FALSE;
            gMain.state = 0;
            return TRUE;
        }
        break;
    }
    return FALSE;
}

// Advances the list scroll animation; TRUE while it is still moving
static bool32 ODex_UpdateListScroll(void)
{
    s16 target = sPokedexView->odexTop * ODEX_ROW_H;
    s16 px = sPokedexView->odexScrollPx;

    if (sPokedexView->odexScrollStep == 0 || px == target)
    {
        sPokedexView->odexScrollStep = 0;
        return FALSE;
    }
    if (px < target)
        px = min(px + sPokedexView->odexScrollStep, target);
    else
        px = max(px - sPokedexView->odexScrollStep, target);
    ODex_SetListScroll(px);
    return px != target;
}

static void ODex_MoveListCursor(s32 newCursor, u32 stepPx)
{
    u16 oldTop = sPokedexView->odexTop;
    u16 newTop;

    if (newCursor < 0)
        newCursor = 0;
    if (newCursor > sPokedexView->pokemonListCount - 1)
        newCursor = sPokedexView->pokemonListCount - 1;
    if (newCursor == sPokedexView->selectedPokemon)
        return;

    // Finish any scroll still running
    if (sPokedexView->odexScrollStep)
        ODex_SetListScroll(oldTop * ODEX_ROW_H);

    sPokedexView->selectedPokemon = newCursor;
    newTop = ODex_TopFor(newCursor, oldTop);
    sPokedexView->odexTop = newTop;
    if (newTop == oldTop + 1 || newTop + 1 == oldTop)
    {
        // Prepare the row that comes in next, then glide the list by one row
        ODex_PrintListRow(newTop > oldTop ? newTop + ODEX_LIST_ROWS : (s32)newTop - 1);
        CopyWindowToVram(ODEX_LWIN_LIST, COPYWIN_GFX);
        sPokedexView->odexScrollStep = stepPx;
        ODex_HighlightRow(newCursor);
        PlaySE(SE_DEX_SCROLL);
    }
    else if (newTop != oldTop)
    {
        ODex_RedrawList();
        PlaySE(SE_DEX_PAGE);
    }
    else
    {
        ODex_HighlightRow(newCursor);
        PlaySE(SE_DEX_SCROLL);
    }
    ODex_ShowListSelection(TRUE);
}

// Up/Down: tap = one row; hold = repeat every 8, then 4, then 2 frames (the list glides at the same pace)
static void ODex_HandleListDpad(void)
{
    s32 dir = 0;
    u32 frames;

    if (sPokedexView->odexCooldown)
        sPokedexView->odexCooldown--;

    if (JOY_NEW(DPAD_UP))
        dir = -1;
    else if (JOY_NEW(DPAD_DOWN))
        dir = 1;
    if (dir)
    {
        sPokedexView->odexRepeat = 0;
        sPokedexView->odexCooldown = 12;
        ODex_MoveListCursor(sPokedexView->selectedPokemon + dir, 2);
        return;
    }

    if (JOY_HELD(DPAD_UP))
        dir = -1;
    else if (JOY_HELD(DPAD_DOWN))
        dir = 1;
    if (dir && sPokedexView->odexCooldown == 0)
    {
        if (sPokedexView->odexRepeat < 255)
            sPokedexView->odexRepeat++;
        frames = sPokedexView->odexRepeat < 4 ? 8 : (sPokedexView->odexRepeat < 12 ? 4 : 2);
        sPokedexView->odexCooldown = frames;
        ODex_MoveListCursor(sPokedexView->selectedPokemon + dir, ODEX_ROW_H / frames);
        return;
    }

    // Left / Right: a page at a time
    if (JOY_NEW(DPAD_LEFT) && sPokedexView->selectedPokemon > 0)
        ODex_MoveListCursor((s32)sPokedexView->selectedPokemon - ODEX_LIST_ROWS, ODEX_ROW_H);
    else if (JOY_NEW(DPAD_RIGHT) && sPokedexView->selectedPokemon < sPokedexView->pokemonListCount - 1)
        ODex_MoveListCursor(sPokedexView->selectedPokemon + ODEX_LIST_ROWS, ODEX_ROW_H);
}

// L / R: TOSA <-> NATIONAL (keeps the same species selected when it is in the other list)
static void ODex_SwitchListMode(void)
{
    u16 dexNum = sPokedexView->pokedexList[sPokedexView->selectedPokemon].dexNum;
    u32 i;

    sPokedexView->dexMode = (sPokedexView->dexMode == DEX_MODE_HOENN) ? DEX_MODE_NATIONAL : DEX_MODE_HOENN;
    CreatePokedexList(sPokedexView->dexMode, sPokedexView->dexOrder);
    sPokedexView->selectedPokemon = 0;
    for (i = 0; i < sPokedexView->pokemonListCount; i++)
    {
        if (sPokedexView->pokedexList[i].dexNum == dexNum)
        {
            sPokedexView->selectedPokemon = i;
            break;
        }
    }
    if (sPokedexView->odexThumbSpriteId != SPRITE_NONE)
        DestroySprite(&gSprites[sPokedexView->odexThumbSpriteId]);
    sPokedexView->odexThumbSpriteId = SPRITE_NONE;
    if (sPokedexView->pokemonListCount > ODEX_LIST_ROWS)
        sPokedexView->odexThumbSpriteId = CreateSprite(&sODexThumbTemplate, ODEX_THUMB_X, ODEX_THUMB_TOP + 8, 0);
    sPokedexView->odexTop = ODex_TopFor(sPokedexView->selectedPokemon, 0);
    ODex_PrintListHeader();
    ODex_RedrawList();
    ODex_ShowListSelection(TRUE);
    PlaySE(SE_DEX_PAGE);
}

