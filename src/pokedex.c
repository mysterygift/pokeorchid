static u16 ODex_TopFor(u16 cursor, u16 top)
{
    s32 t = top;
    s32 maxTop = sPokedexView->pokemonListCount > ODEX_LIST_ROWS ? sPokedexView->pokemonListCount - ODEX_LIST_ROWS : 0;

    if (cursor < t + ODEX_CURSOR_MARGIN)
        t = cursor - ODEX_CURSOR_MARGIN;
    if (cursor > t + ODEX_LIST_ROWS - 1 - ODEX_CURSOR_MARGIN)
        t = cursor - (ODEX_LIST_ROWS - 1 - ODEX_CURSOR_MARGIN);
    if (t > maxTop)
        t = maxTop;
    if (t < 0)
        t = 0;
    return t;
}

// One pill row of the list, drawn into its ring slot (16px tall)
static void ODex_PrintListRow(s32 entry)
{
    struct PokedexListItem *item;
    u8 str[8];
    u32 y;
    const u8 *name;

    if (entry < 0)
        return;
    y = (entry % ODEX_RING_ROWS) * ODEX_ROW_H;
    FillWindowPixelRect(ODEX_LWIN_LIST, PIXEL_FILL(0), 0, y, ODEX_LIST_WIN_WIDTH * 8, ODEX_ROW_H);
    if (entry >= sPokedexView->pokemonListCount)
        return;   // past the end: the grid shows through

    item = &sPokedexView->pokedexList[entry];
    BlitBitmapToWindow(ODEX_LWIN_LIST, gOrchidDexRow_Gfx, 0, y, ODEX_LIST_WIN_WIDTH * 8, ODEX_ROW_H);
    ODex_FormatNumber(str, item->dexNum);
    if (P_SKIP_POKEDEX_GAPS == SKIP_GAPS_EXCEPT_ONE && !item->seen)
    {
        for (u32 i = 0; str[i] != EOS; i++)
            str[i] = CHAR_HYPHEN;
    }
    ODex_Print(ODEX_LWIN_LIST, FONT_NARROW, str, ODEX_ROW_NUM_X, y, sODexText_Ink);
    if (item->seen)
    {
        name = GetSpeciesName(NationalPokedexNumToSpeciesForm(item->dexNum));
        ODex_Print(ODEX_LWIN_LIST, GetFontIdToFit(name, FONT_NARROW, 0, ODEX_ROW_BALL_X - ODEX_ROW_NAME_X - 2),
                   name, ODEX_ROW_NAME_X, y, sODexText_Ink);
    }
    else
    {
        ODex_Print(ODEX_LWIN_LIST, FONT_NARROW, sODexText_Dashes, ODEX_ROW_NAME_X, y, sODexText_InkSoft);
    }
    if (item->owned)
        BlitBitmapToWindow(ODEX_LWIN_LIST, gOrchidDexBall_Gfx, ODEX_ROW_BALL_X, y + ODEX_ROW_BALL_Y, 8, 8);
}

// The cursor row is the gold pill: palette 1 on its 17x2 cells
static void ODex_HighlightRow(u16 entry)
{
    u32 slot;

    slot = sPokedexView->odexHighlight % ODEX_RING_ROWS;
    ODex_SetCellPalette(2, ODEX_LIST_WIN_LEFT, slot * 2, ODEX_LIST_WIN_WIDTH, 2, ODEX_PAL_NORMAL);
    slot = entry % ODEX_RING_ROWS;
    ODex_SetCellPalette(2, ODEX_LIST_WIN_LEFT, slot * 2, ODEX_LIST_WIN_WIDTH, 2, ODEX_PAL_SELECTED);
    sPokedexView->odexHighlight = entry;
    CopyBgTilemapBufferToVram(2);
}

static void ODex_SetListScroll(s16 px)
{
    sPokedexView->odexScrollPx = px;
    SetGpuReg(REG_OFFSET_BG2VOFS, (px - ODEX_LIST_Y) & 0xFF);
    if (sPokedexView->odexThumbSpriteId != SPRITE_NONE)
    {
        s32 range = (sPokedexView->pokemonListCount - ODEX_LIST_ROWS) * ODEX_ROW_H;
        s32 y = ODEX_THUMB_TOP + (range > 0 ? ODEX_THUMB_SPAN * px / range : 0);
        gSprites[sPokedexView->odexThumbSpriteId].y = y + 8;
    }
}

static void ODex_RedrawList(void)
{
    s32 i;

    FillWindowPixelBuffer(ODEX_LWIN_LIST, PIXEL_FILL(0));
    for (i = (s32)sPokedexView->odexTop - 1; i <= sPokedexView->odexTop + ODEX_LIST_ROWS; i++)
        ODex_PrintListRow(i);
    CopyWindowToVram(ODEX_LWIN_LIST, COPYWIN_GFX);
    sPokedexView->odexScrollStep = 0;
    ODex_SetListScroll(sPokedexView->odexTop * ODEX_ROW_H);
    ODex_HighlightRow(sPokedexView->selectedPokemon);
}

