// Called every frame from CB2_Pokedex: the BW grid scrolls diagonally down-right, 1px / 4 frames
static void ODex_UpdateGrid(void)
{
    if ((++sODexGridTimer & 3) == 0)
        sODexGridPos++;
    if (sODexGridBg != 0)
    {
        SetGpuReg(REG_OFFSET_BG0HOFS + (sODexGridBg - 1) * 4, (-sODexGridPos) & 0xF);
        SetGpuReg(REG_OFFSET_BG0VOFS + (sODexGridBg - 1) * 4, (-sODexGridPos) & 0xF);
    }
}

// Ease-out (1 - (1 - u)^2) of frame t of ODEX_FADE_FRAMES, in 1/256ths
static s32 ODex_Ease(s32 t)
{
    s32 r = ODEX_FADE_FRAMES - t;
    return 256 - 256 * r * r / (ODEX_FADE_FRAMES * ODEX_FADE_FRAMES);
}

static void ODex_FillGridMap(u8 bg)
{
    u16 *map = GetBgTilemapBuffer(bg);
    u32 x, y;

    for (y = 0; y < 32; y++)
    {
        for (x = 0; x < 32; x++)
            map[y * 32 + x] = (ODEX_GRID_TILE_BASE + (x & 1) + (y & 1) * 2) | (ODEX_PAL_GRID << 12);
    }
    CopyBgTilemapBufferToVram(bg);
    sODexGridBg = bg + 1;
    ODex_UpdateGrid();
}

// Patches the palette bits of a block of tilemap cells (selected = gold palette swap)
static void ODex_SetCellPalette(u8 bg, u32 left, u32 top, u32 width, u32 height, u32 pal)
{
    u16 *map = GetBgTilemapBuffer(bg);
    u32 x, y;

    for (y = top; y < top + height; y++)
    {
        for (x = left; x < left + width; x++)
            map[y * 32 + x] = (map[y * 32 + x] & 0x0FFF) | (pal << 12);
    }
}

