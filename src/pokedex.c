// Orchid entry page (INFO / AREA tabs). Loads darkened (BLDY on BG2/BG3; the grid on BG1 and the
// OBJ stay lit), then brightens in over 12 frames.
void Task_LoadInfoScreen(u8 taskId)
{
    if (Task_TryLoadInfoScreen_HGSS(taskId))
        return;

    switch (gMain.state)
    {
    case 0:
    default:
        if (!gPaletteFade.active)
        {
            sPokedexView->currentPage = PAGE_INFO;
            gPokedexVBlankCB = gMain.vblankCallback;
            ResetOtherVideoRegisters(DISPCNT_OBJ_ON | DISPCNT_BG1_ON);
            SetBgAttribute(1, BG_ATTR_PRIORITY, 3);
            SetGpuReg(REG_OFFSET_BLDCNT, ODEX_BLD_TARGETS);
            SetGpuReg(REG_OFFSET_BLDY, 16);
            gMain.state = 1;
        }
        break;
    case 1:
        DecompressAndLoadBgGfxUsingHeap(3, gOrchidDexEntry_Gfx, ODEX_ENTRY_NUM_TILES * TILE_SIZE_4BPP, 0, 0);
        ODex_FillGridMap(1);
        ShowBg(1);
        LoadPalette(gOrchidDexScreen_Pal, BG_PLTT_ID(0), 3 * PLTT_SIZE_4BPP);
        ODex_DrawEntryArt(sPokedexView->odexTab);
        PutWindowTilemap(WIN_INFO);
        CopyBgTilemapBufferToVram(2);
        gMain.state++;
        break;
    case 2:
        ODex_PrintEntry(sPokedexView->odexTab);
        gMain.state++;
        break;
    case 3:
        if (!gTasks[taskId].tMonSpriteDone)
            ODex_ShowPic(sPokedexListItem->dexNum, TRUE, ODEX_E_DAIS_X, ODEX_E_DAIS_STAGE_Y, gTasks[taskId].tScrolling);
        gTasks[taskId].tMonSpriteId = sPokedexView->odexPicSpriteId;
        ODex_LoadSpriteGfx();
        ODex_CreateTypeIcons();
        ODex_CreateArrows(ODEX_TAB_ARROW_L_X, ODEX_TAB_ARROW_R_X, ODEX_TAB_ARROW_Y);
        ODex_HideTypeIcons();
        ODex_SetArrowsVisible(FALSE);
        gMain.state++;
        break;
    case 4:
        SetGpuReg(REG_OFFSET_DISPCNT, DISPCNT_OBJ_1D_MAP | DISPCNT_OBJ_ON);
        HideBg(0);
        ShowBg(1);
        ShowBg(2);
        ShowBg(3);
        SetVBlankCallback(gPokedexVBlankCB);
        gTasks[taskId].tFadeTimer = ODEX_FADE_FRAMES;
        gMain.state++;
        break;
    case 5:
        ODex_UpdatePicSlide();
        if (gTasks[taskId].tFadeTimer)
        {
            gTasks[taskId].tFadeTimer--;
            SetGpuReg(REG_OFFSET_BLDY, gTasks[taskId].tFadeTimer * 16 / ODEX_FADE_FRAMES);
            break;
        }
        SetGpuReg(REG_OFFSET_BLDCNT, 0);
        ODex_ShowEntrySprites(sPokedexView->odexTab);
        gMain.state++;
        if (!gTasks[taskId].tSkipCry)
        {
            StopCryAndClearCrySongs();
            PlayCry_NormalNoDucking(NationalPokedexNumToSpeciesForm(sPokedexListItem->dexNum), 0, CRY_VOLUME_RS, CRY_PRIORITY_NORMAL);
        }
        else
        {
            gMain.state++;
        }
        break;
    case 6:
        ODex_UpdatePicSlide();
        if (!IsCryPlayingOrClearCrySongs())
            gMain.state++;
        break;
    case 7:
        ODex_UpdatePicSlide();
        gTasks[taskId].tScrolling = FALSE;
        gTasks[taskId].tMonSpriteDone = FALSE; // Reload next time screen comes up
        gTasks[taskId].tBgLoaded = TRUE;
        gTasks[taskId].tSkipCry = TRUE;
        gTasks[taskId].func = Task_HandleInfoScreenInput;
        gMain.state = 0;
        break;
    }
}

