static void ODex_CreateTypeIcons(void)
{
    u32 i;

    for (i = 0; i < 2; i++)
    {
        if (sPokedexView->odexTypeSpriteIds[i] == SPRITE_NONE)
        {
            u8 spriteId = CreateSprite(&gSpriteTemplate_MoveTypes, 0, 0, 0);
            gSprites[spriteId].oam.priority = 0;
            gSprites[spriteId].invisible = TRUE;
            sPokedexView->odexTypeSpriteIds[i] = spriteId;
        }
    }
}

static void ODex_HideTypeIcons(void)
{
    u32 i;

    for (i = 0; i < 2; i++)
    {
        if (sPokedexView->odexTypeSpriteIds[i] != SPRITE_NONE)
            gSprites[sPokedexView->odexTypeSpriteIds[i]].invisible = TRUE;
    }
}

static void ODex_SetTypeIcon(u32 i, enum Type type, s16 x, s16 y)
{
    struct Sprite *sprite;

    if (sPokedexView->odexTypeSpriteIds[i] == SPRITE_NONE)
        return;
    sprite = &gSprites[sPokedexView->odexTypeSpriteIds[i]];
    StartSpriteAnim(sprite, type);
    sprite->oam.paletteNum = gTypesInfo[type].palette;
    sprite->x = x + 16;
    sprite->y = y + 8;
    sprite->invisible = FALSE;
}

// Type icons of a species. centreX >= 0: centred under the dais; otherwise left-aligned at -centreX.
static void ODex_ShowTypes(enum Species species, s16 centreX, s16 leftX, s16 y)
{
    enum Type type1 = GetSpeciesType(species, 0);
    enum Type type2 = GetSpeciesType(species, 1);
    s16 x = leftX;

    ODex_HideTypeIcons();
    if (centreX >= 0)
        x = centreX - (type1 == type2 ? 16 : 34);
    ODex_SetTypeIcon(0, type1, x, y);
    if (type1 != type2)
        ODex_SetTypeIcon(1, type2, x + 36, y);
}

static void ODex_CreateArrows(s16 leftX, s16 rightX, s16 y)
{
    if (sPokedexView->odexArrowSpriteIds[0] == SPRITE_NONE)
    {
        sPokedexView->odexArrowSpriteIds[0] = CreateSprite(&sODexArrowTemplate, leftX, y, 0);
        sPokedexView->odexArrowSpriteIds[1] = CreateSprite(&sODexArrowTemplate, rightX, y, 0);
        // sprite->hFlip is XORed into the OAM flip bits by the anim code
        gSprites[sPokedexView->odexArrowSpriteIds[1]].hFlip = TRUE;
    }
}

