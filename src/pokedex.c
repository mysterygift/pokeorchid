static u8* ConvertMeasurementToMetricString(u32 num, u32* index)
{
    u8* string = Alloc(WEIGHT_HEIGHT_STR_MEM);
    bool32 outputted = FALSE;
    u32 result;

    result = num / 1000;
    if (result == 0)
    {
        string[(*index)++] = CHAR_SPACER;
        outputted = FALSE;
    }
    else
    {
        string[(*index)++] = CHAR_0 + result;
        outputted = TRUE;
    }

    result = (num % 1000) / 100;
    if (result == 0 && !outputted)
    {
        string[(*index)++] = CHAR_SPACER;
        outputted = FALSE;
    }
    else
    {
        string[(*index)++] = CHAR_0 + result;
        outputted = TRUE;
    }

    string[(*index)++] = CHAR_0 + ((num % 1000) % 100) / 10;
    string[(*index)++] = CHAR_DEC_SEPARATOR;
    string[(*index)++] = CHAR_0 + ((num % 1000) % 100) % 10;
    string[(*index)++] = CHAR_SPACE;

    return string;
}

s8 GetSetPokedexFlag(enum NationalDexOrder nationalDexNo, u8 caseID)
{
    u32 index, bit, mask;
    s8 retVal = 0;

    nationalDexNo--;
    index = nationalDexNo / 8;
    bit = nationalDexNo % 8;
    mask = 1 << bit;

    switch (caseID)
    {
    case FLAG_GET_SEEN:
        retVal = ((gSaveBlock1Ptr->dexSeen[index] & mask) != 0);
        break;
    case FLAG_GET_CAUGHT:
         retVal = ((gSaveBlock1Ptr->dexCaught[index] & mask) != 0);
        break;
    case FLAG_SET_SEEN:
        gSaveBlock1Ptr->dexSeen[index] |= mask;
        break;
    case FLAG_SET_CAUGHT:
        gSaveBlock1Ptr->dexCaught[index] |= mask;
        break;
    }

    return retVal;
}

