// constants are generated by dev_scripts/orchid_ui/export_summary.py
// (graphics/summary_screen/orchid/, src/data/pokemon_summary_orchid.h).
//
// Layers:
//   BG3  BW grid (scrolls down-right 1px / 4 frames)
//   BG2  right-hand page art, 64x32 map: pages slide by BG2HOFS; WIN0 hides BG2 left of x 90
//   BG1  header tabs + left column (+ the move detail tray); button hints in rows 18-19
//   BG0  text windows
//   OBJ  front pic, ball, status tag, held item, type icons, category tag, red chevrons
// Pages: INFO, SKILLS (A cycles STATS / IVs / EVs), BATTLE MOVES. The contest page is not drawn
