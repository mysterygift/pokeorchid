// "{LV}18" in the small font (the ROM's Lv ligature)
static void OSum_FormatLevel(u8 *dst, u32 level)
{
    u8 *end = StringCopy(dst, gText_LevelSymbol);
    ConvertIntToDecimalStringN(end, level, STR_CONV_MODE_LEFT_ALIGN, 3);
}

static void OSum_FormatThousands(u8 *dst, u32 value)
{
    u8 digits[12];
    u32 i, len;

    ConvertIntToDecimalStringN(digits, value, STR_CONV_MODE_LEFT_ALIGN, 10);
    len = StringLength(digits);
    for (i = 0; i < len; i++)
    {
        if (i != 0 && (len - i) % 3 == 0)
            *dst++ = CHAR_COMMA;
        *dst++ = digits[i];
    }
    *dst = EOS;
}

