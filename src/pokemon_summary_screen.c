// Round half to even (Python's round(), as the mockup)
static u32 OSum_RoundDiv(u32 num, u32 den)
{
    u32 q, r;

    if (den == 0)
        return 0;
    q = num / den;
    r = num % den;
    if (2 * r > den || (2 * r == den && (q & 1)))
        q++;
    return q;
}

static void OSum_PaintBar(u32 id, u32 fill, u8 light, u8 dark)
{
    const struct OSumBar *bar = &sOSumBars[id];
    u8 *buf = sMonSummaryScreen->barBuffer;
    u32 i, y;

    if (fill > OSUM_BAR_W)
        fill = OSUM_BAR_W;
    CpuCopy16(&gOrchidSummaryBars_Gfx[(bar->tile - OSUM_BAR_TILES_FIRST) * TILE_SIZE_4BPP], buf, bar->count * TILE_SIZE_4BPP);
    for (i = 1; i <= fill; i++)
    {
        for (y = 1; y <= 3; y++)
        {
            u32 px = bar->x + i, py = bar->y + y;
            u32 tile = (py / 8 - bar->row0) * bar->cols + (px / 8 - bar->col0);
            u8 *p = &buf[tile * TILE_SIZE_4BPP + (py % 8) * 4 + (px % 8) / 2];
            u8 c = (y == 1) ? light : dark;

            if (px & 1)
                *p = (*p & 0x0F) | (c << 4);
            else
                *p = (*p & 0xF0) | c;
        }
    }
    CpuCopy16(buf, (void *)(BG_CHAR_ADDR(2) + bar->tile * TILE_SIZE_4BPP), bar->count * TILE_SIZE_4BPP);
}

