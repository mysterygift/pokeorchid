static void Task_HandleInput(u8 taskId)
{
    if (MenuHelpers_ShouldWaitForLinkRecv() != TRUE && !gPaletteFade.active)
    {
        if (JOY_NEW(DPAD_UP))
        {
            ChangeSummaryPokemon(taskId, -1);
        }
        else if (JOY_NEW(DPAD_DOWN))
        {
            ChangeSummaryPokemon(taskId, 1);
        }
        else if (JOY_NEW(DPAD_LEFT))
        {
            ChangePage(taskId, -1);
        }
        else if (JOY_NEW(DPAD_RIGHT))
        {
            ChangePage(taskId, 1);
        }
        else if (JOY_NEW(A_BUTTON))
        {
            if (sMonSummaryScreen->currPageIndex == PSS_PAGE_INFO)
            {
                if (ShouldShowRename())
                {
                    if (sMonSummaryScreen->isBoxMon)
                    {
                        gSpecialVar_0x8004 = PC_MON_CHOSEN;
                        gSpecialVar_MonBoxPos = sMonSummaryScreen->curMonIndex;
                        gSpecialVar_MonBoxId = StorageGetCurrentBox();
                    }
                    else
                    {
                        gSpecialVar_0x8004 = sMonSummaryScreen->curMonIndex;
                    }
                    sMonSummaryScreen->callback = CB2_PssChangePokemonNickname;
                }

                StopPokemonAnimations();
                PlaySE(SE_SELECT);
                BeginCloseSummaryScreen(taskId);
            }
            else if (IS_MOVE_PAGE(sMonSummaryScreen->currPageIndex))
            {
                PlaySE(SE_SELECT);
                SwitchToMoveSelection(taskId);
            }
            else if (sMonSummaryScreen->currPageIndex == PSS_PAGE_SKILLS && ShouldShowIvEvPrompt())
            {
                // A cycles STATS -> IVs -> EVs: header label, hint, page art, bars and text
                IncrementSkillsStatsMode(sMonSummaryScreen->skillsPageMode);
                OSum_DrawPage();
                PlaySE(SE_SELECT);
            }
        }
        else if (JOY_NEW(B_BUTTON))
        {
            StopPokemonAnimations();
            PlaySE(SE_SELECT);
            BeginCloseSummaryScreen(taskId);
        }
        else if (DEBUG_POKEMON_SPRITE_VISUALIZER && JOY_NEW(SELECT_BUTTON) && !gMain.inBattle)
        {
            sMonSummaryScreen->callback = CB2_Pokemon_Sprite_Visualizer;
            StopPokemonAnimations();
            PlaySE(SE_SELECT);
            CloseSummaryScreen(taskId);
        }
        else if (ShouldShowMoveRelearner() && IS_MOVE_PAGE(sMonSummaryScreen->currPageIndex))
        {
            HandleMoveRelearnerInput(taskId);
        }
    }
}

static u8 IncrementSkillsStatsMode(u8 mode)
{
    switch (mode)
    {
    case SUMMARY_SKILLS_MODE_STATS:
        if (P_SUMMARY_SCREEN_EV_ONLY)
            sMonSummaryScreen->skillsPageMode = SUMMARY_SKILLS_MODE_EVS;
        else
            sMonSummaryScreen->skillsPageMode = SUMMARY_SKILLS_MODE_IVS;
        break;
    case SUMMARY_SKILLS_MODE_IVS:
        if (P_SUMMARY_SCREEN_IV_ONLY)
            sMonSummaryScreen->skillsPageMode = SUMMARY_SKILLS_MODE_STATS;
        else
            sMonSummaryScreen->skillsPageMode = SUMMARY_SKILLS_MODE_EVS;
        break;
    case SUMMARY_SKILLS_MODE_EVS:
    default:
        sMonSummaryScreen->skillsPageMode = SUMMARY_SKILLS_MODE_STATS;
        break;
    }
    return sMonSummaryScreen->skillsPageMode;
}

