static void OSum_PaintBars(void)
{
    struct PokeSummary *sum = &sMonSummaryScreen->summary;
    u32 fill, i;

    if (sMonSummaryScreen->skillsPageMode == SUMMARY_SKILLS_MODE_STATS)
    {
        // Gen 3 GetHPBarLevel: thresholds in bar pixels (> 24 green, > 9 yellow, else red)
        fill = 0;
        if (sum->currentHP != 0 && sum->maxHP != 0)
        {
            fill = sum->currentHP * OSUM_BAR_W / sum->maxHP;
            if (fill == 0)
                fill = 1;
        }
        i = fill > 24 ? OSUM_BAR_GREEN : (fill > 9 ? OSUM_BAR_YELLOW : OSUM_BAR_RED);
        OSum_PaintBar(OSUM_BAR_HP, fill, i, i + 1);
    }
    else
    {
        static const u8 sBarIds[NUM_STATS] = {
            [STAT_HP] = OSUM_BAR_IV_HP, [STAT_ATK] = OSUM_BAR_IV_ATK, [STAT_DEF] = OSUM_BAR_IV_DEF,
            [STAT_SPATK] = OSUM_BAR_IV_SPA, [STAT_SPDEF] = OSUM_BAR_IV_SPD, [STAT_SPEED] = OSUM_BAR_IV_SPE,
        };
        u32 max = sMonSummaryScreen->skillsPageMode == SUMMARY_SKILLS_MODE_IVS ? MAX_PER_STAT_IVS : MAX_PER_STAT_EVS;

        for (i = 0; i < NUM_STATS; i++)
        {
            u32 v = OSum_IvEvValue(i);
            fill = OSum_RoundDiv(OSUM_BAR_W * v, max);
            if (v != 0 && fill == 0)
                fill = 1;
            OSum_PaintBar(sBarIds[i], fill, OSUM_C_SELECT_LIGHT, OSUM_C_SELECT_DARK);
        }
    }
    fill = 0;
    if (sum->level < MAX_LEVEL)
    {
        u32 lo = gExperienceTables[gSpeciesInfo[sum->species].growthRate][sum->level];
        u32 hi = gExperienceTables[gSpeciesInfo[sum->species].growthRate][sum->level + 1];
        if (sum->exp > lo && hi > lo)
            fill = OSum_RoundDiv(OSUM_BAR_W * (sum->exp - lo), hi - lo);
    }
    OSum_PaintBar(OSUM_BAR_EXP, fill, OSUM_BAR_EXP, OSUM_BAR_EXP + 1);
}

