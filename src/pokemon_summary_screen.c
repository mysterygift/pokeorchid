        return right;
    up = sOSumStatShort[nature->statUp];
    down = sOSumStatShort[nature->statDown];
    x0 = x = right - (8 + GetStringWidth(FONT_SMALL, up, 0) + 3 + 8 + GetStringWidth(FONT_SMALL, down, 0));
