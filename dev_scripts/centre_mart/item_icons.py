def build(name):
    legend, text = ICONS[name]
    rows = [r for r in text.split("\n") if r.strip()]
    assert len(rows) == 24, (name, len(rows))
    pal = [BG] + list(legend.values())
    assert len(pal) <= 16, name
    keys = list(legend)
    im = Image.new("P", (24, 24), 0)
    flat = pal + [(0, 0, 0)] * (16 - len(pal))
    im.putpalette([v for c in flat for v in c])
    px = im.load()
    for y, row in enumerate(rows):
        assert len(row) == 24, (name, y, len(row), row)
        for x, ch in enumerate(row):
            if ch != ".":
                px[x, y] = keys.index(ch) + 1
    return im, flat


def main():
    sheet = Image.new("RGB", (len(ICONS) * 28 + 4, 32), (248, 248, 240))
    for i, name in enumerate(ICONS):
        im, pal = build(name)
        im.save(os.path.join(ROOT, "graphics", "items", "icons", name + ".png"), bits=4, optimize=False)
        with open(os.path.join(ROOT, "graphics", "items", "icon_palettes", name + ".pal"), "w", newline="\r\n") as f:
            f.write("JASC-PAL\n0100\n16\n")
            for c in pal:
                f.write(f"{c[0]} {c[1]} {c[2]}\n")
        rgba = im.convert("RGBA")
        data = [(r, g, b, 0) if (r, g, b) == BG else (r, g, b, 255) for r, g, b, _ in list(rgba.getdata())]
        rgba.putdata(data)
        sheet.paste(rgba, (4 + i * 28, 4), rgba)
    os.makedirs(os.path.join(HERE, "out"), exist_ok=True)
    p = os.path.join(HERE, "out", "item_icons_8x.png")
    sheet.resize((sheet.width * 8, sheet.height * 8), Image.NEAREST).save(p)
    print(p)


if __name__ == "__main__":
    main()
