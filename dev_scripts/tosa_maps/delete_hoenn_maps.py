#!/usr/bin/env python3
"""
Delete the vanilla Hoenn maps that sit on the map sections renamed for Tosa (user, 2026-11-19:
"Delete the Hoenn maps"). Their places are now the Tosa placeholder maps (placeholders.py /
tosa_stations.py); the Hoenn maps were showing up as Tosa places next to them.

Deleted: every map on a Tosa-renamed section (Petalburg, Slateport, Mauville, Rustboro, Lilycove,
Mossdeep, Sootopolis, Ever Grande, Routes 102-114 and their houses, Mt. Chimney, Petalburg Woods,
Victory Road, New Mauville) except the Tosa-built maps, plus the underwater maps whose surface map
goes (Route 105, Sootopolis).
Kept: the Ever Grande League interiors (Elite Four, Champion, Hall of Fame) - moved to
MAPSEC_PKMN_LEAGUE for the future Pokemon League.

Everything that pointed at a deleted map:
  * connections to it are dropped; warps into it loop back to themselves (warp ids elsewhere keep
    their numbering);
  * deleted MAP_ ids stay defined by mapjson ("unused maps"; emitted as an enum so asm scripts still
    assemble); their LOCALID_ ids get dummies in include/constants/deleted_hoenn_maps.h (included
    from constants/maps.h); the Fly table in src/region_map.c points the renamed sections at the
    Tosa maps;
  * heal locations of deleted maps are removed and their ids aliased to the Tosa Centres'
    (include/constants/heal_location_aliases.h), so Fly / whiteout land in the placeholders;
  * wild encounters move to the replacement map when it has none of its own.

One-shot: run once from the repo root (python3 dev_scripts/tosa_maps/delete_hoenn_maps.py).
"""
import glob
import json
import os
import re
import shutil
from collections import OrderedDict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
P = lambda *p: os.path.join(ROOT, *p)

TOWNS = {"PETALBURG_CITY": "TIMAH_CITY", "SLATEPORT_CITY": "CHANGU_CITY", "MAUVILLE_CITY": "SENOKO_CITY",
         "RUSTBORO_CITY": "INKA_CITY", "LILYCOVE_CITY": "JURAN_CITY", "MOSSDEEP_CITY": "MOONGROVE_CITY",
         "SOOTOPOLIS_CITY": "CORRAL_CITY", "EVER_GRANDE_CITY": "CHALLENGER_GATE"}
REPLACE = {"MAP_" + k: "MAP_" + v for k, v in TOWNS.items()}
for k, v in TOWNS.items():
    REPLACE["MAP_%s_POKEMON_CENTER_1F" % k] = "MAP_%s_POKEMON_CENTER_1F" % v
    REPLACE["MAP_%s_MART" % k] = "MAP_%s_MART" % v
for n in range(102, 115):
    REPLACE["MAP_ROUTE%d" % n] = "MAP_ROUTE%d" % (n + 200)
REPLACE.update({"MAP_ROUTE311": "MAP_ROUTE311_WEST", "MAP_ROUTE111": "MAP_ROUTE311_WEST",
                "MAP_MT_CHIMNEY": "MAP_MT_BATOK_3F", "MAP_PETALBURG_WOODS": "MAP_MOONGROVE_MARSH",
                "MAP_VICTORY_ROAD_1F": "MAP_CHALLENGERS_TRAIL_1F", "MAP_VICTORY_ROAD_B1F": "MAP_CHALLENGERS_TRAIL_2F",
                "MAP_VICTORY_ROAD_B2F": "MAP_CHALLENGERS_TRAIL_3F", "MAP_NEW_MAUVILLE_ENTRANCE": "MAP_POWER_PLANT",
                "MAP_NEW_MAUVILLE_INSIDE": "MAP_POWER_PLANT"})
REPLACE.pop("MAP_ROUTE311", None)
HEAL = {"HEAL_LOCATION_%s" % k: "HEAL_LOCATION_%s" % v for k, v in TOWNS.items()}
KEEP_EVER_GRANDE = re.compile(r"^EverGrandeCity_(PokemonLeague_1F|PokemonLeague_2F|Hall\d|\w+sRoom|HallOfFame)$")
EXTRA = {"Underwater_Route105", "Underwater_SootopolisCity"}


def load(path):
    return json.load(open(path), object_pairs_hook=OrderedDict)


def dump(path, data):
    with open(path, "w") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write("\n")


def write_map_header(local_ids):
    """Deleted maps' MAP_ ids are defined by mapjson ("unused maps", from required_map_defines.json;
    Orchid's mapjson emits them as an enum so asm scripts accept them). Their LOCALID_ ids, which
    vanilla C and shared scripts still name, get dummy values here (only dead code uses them)."""
    L = ["// GENERATED by dev_scripts/tosa_maps/delete_hoenn_maps.py - Hoenn maps deleted for Tosa.",
         "// Local object ids of the deleted maps, still named by vanilla code; only dead paths use them.",
         "#ifndef GUARD_CONSTANTS_DELETED_HOENN_MAPS_H", "#define GUARD_CONSTANTS_DELETED_HOENN_MAPS_H", ""]
    for i, lid in enumerate(local_ids):
        L.append("#define %-48s %d" % (lid, 100 + i % 150))
    L += ["", "#endif // GUARD_CONSTANTS_DELETED_HOENN_MAPS_H", ""]
    open(P("include", "constants", "deleted_hoenn_maps.h"), "w").write("\n".join(L))


def main():
    tags = load(P("dev_scripts", "region_map_tagger", "tags.json"))
    aliases = open(P("include", "constants", "region_map_section_aliases.h")).read()
    # Tosa ids of renamed vanilla Hoenn slots. The alias header also holds the Tiksi renames of the
    # Kanto/Sevii block, so only sections outside that index range count.
    pairs = dict(re.findall(r"#define\s+(MAPSEC_\w+)\s+(MAPSEC_\w+)", aliases))
    resolve = lambda i: pairs.get(i, i)
    secs = [x["id"] for x in load(P("src", "data", "region_map", "region_map_sections.json"))["map_sections"]]
    k0, k1 = secs.index(resolve("MAPSEC_PALLET_TOWN")), secs.index(resolve("MAPSEC_SPECIAL_AREA"))
    renamed = {new for new in pairs.values() if new in secs and not (k0 <= secs.index(new) <= k1)}
    renamed.discard("MAPSEC_SOUTH_TOSA_RESERVE_1")                           # Orchid-built
    mg = load(P("data", "maps", "map_groups.json"))
    tosa_built = set(mg.get("gMapGroup_TosaOverworld", []) + mg.get("gMapGroup_TosaRail", []))
    maps = {}
    for f in glob.glob(P("data", "maps", "*", "map.json")):
        m = load(f)
        maps[m["name"]] = m
    doomed, kept_league = set(), []
    for name, m in maps.items():
        if name in tosa_built:
            continue
        if m.get("region_map_section") in renamed or name in EXTRA:
            if KEEP_EVER_GRANDE.match(name):
                kept_league.append(name)
            else:
                doomed.add(name)
    protected = set(mg.get("gMapGroup_Tiksi", []))
    assert not doomed & protected, "would delete Tiksi maps: %s" % sorted(doomed & protected)
    ids = {maps[n]["id"]: n for n in doomed}
    by_id = {m["id"]: m for m in maps.values()}
    print("deleting %d maps, keeping %d League rooms" % (len(doomed), len(kept_league)))

    # remaining maps: drop connections, loop warps, move the League rooms
    for name, m in maps.items():
        if name in doomed:
            continue
        changed = False
        conns = m.get("connections") or []
        keep = [c for c in conns if c["map"] not in ids]
        if len(keep) != len(conns):
            m["connections"] = keep or None
            changed = True
        for i, w in enumerate(m.get("warp_events", [])):
            if w["dest_map"] in ids:
                w["dest_map"], w["dest_warp_id"] = m["id"], str(i)
                changed = True
        if name in kept_league:
            m["region_map_section"] = "MAPSEC_PKMN_LEAGUE"
            changed = True
        if changed:
            dump(P("data", "maps", name, "map.json"), m)

    # map groups, layouts, script includes, folders
    used_layouts = {m["layout"] for n, m in maps.items() if n not in doomed}
    for g in list(mg["group_order"]):
        mg[g] = [n for n in mg[g] if n not in doomed]
        if not mg[g]:
            mg["group_order"].remove(g)
            del mg[g]
    dump(P("data", "maps", "map_groups.json"), mg)
    lj = load(P("data", "layouts", "layouts.json"))
    gone = [l for l in lj["layouts"] if l["id"] not in used_layouts and
            any(maps[n]["layout"] == l["id"] for n in doomed)]
    lj["layouts"] = [l for l in lj["layouts"] if l not in gone]
    dump(P("data", "layouts", "layouts.json"), lj)
    for l in gone:
        d = os.path.dirname(P(l["blockdata_filepath"]))
        if os.path.isdir(d):
            shutil.rmtree(d)
    es = open(P("data", "event_scripts.s")).read().split("\n")
    es = [ln for ln in es if not any('data/maps/%s/' % n in ln for n in doomed)]
    open(P("data", "event_scripts.s"), "w").write("\n".join(es))
    for n in doomed:
        shutil.rmtree(P("data", "maps", n))

    # heal locations
    hp = P("src", "data", "heal_locations.json")
    heal = load(hp)
    removed = [h["id"] for h in heal["heal_locations"] if h["map"] in ids or h.get("respawn_map") in ids]
    heal["heal_locations"] = [h for h in heal["heal_locations"] if h["id"] not in removed]
    dump(hp, heal)

    # wild encounters: move to the replacement map if it has none
    wp = P("src", "data", "wild_encounters.json")
    wild = load(wp)
    moved = dropped = 0
    for grp in wild["wild_encounter_groups"]:
        encs = grp.get("encounters", [])
        have = {e.get("map") for e in encs}
        out = []
        for e in encs:
            mp = e.get("map")
            if mp in ids:
                rep = REPLACE.get(mp)
                if rep and rep not in have and rep not in ids:
                    e["map"] = rep
                    e["base_label"] = "g" + by_id[rep]["name"]
                    have.add(rep)
                    moved += 1
                    out.append(e)
                else:
                    dropped += 1
                continue
            out.append(e)
        grp["encounters"] = out
    dump(wp, wild)

    # alias headers
    write_map_header(sorted({o["local_id"] for n in doomed for o in maps[n]["object_events"] if o.get("local_id")}))
    H = ["// GENERATED by dev_scripts/tosa_maps/delete_hoenn_maps.py - heal locations of deleted Hoenn maps.",
         "#ifndef GUARD_CONSTANTS_HEAL_LOCATION_ALIASES_H", "#define GUARD_CONSTANTS_HEAL_LOCATION_ALIASES_H", ""]
    for hid in sorted(removed):
        H.append("#define %-48s %s" % (hid, HEAL.get(hid, "HEAL_LOCATION_NONE")))
    H += ["", "#endif // GUARD_CONSTANTS_HEAL_LOCATION_ALIASES_H", ""]
    open(P("include", "constants", "heal_location_aliases.h"), "w").write("\n".join(H))
    # Fly table: the renamed sections fly to their Tosa maps
    rp = P("src", "region_map.c")
    rc = open(rp).read()
    i = rc.index("static const u8 sMapHealLocations[][3] =")
    j = rc.index("};", i)
    tab = rc[i:j]
    for old, new in REPLACE.items():
        if old in ids:
            tab = tab.replace("MAP_GROUP(%s), MAP_NUM(%s)" % (old, old), "MAP_GROUP(%s), MAP_NUM(%s)" % (new, new))
    for old, new in HEAL.items():
        tab = tab.replace(old + "}", new + "}")
    open(rp, "w").write(rc[:i] + tab + rc[j:])
    print("layouts removed %d, heal locations removed %d, wild moved %d dropped %d" % (len(gone), len(removed), moved, dropped))
    print("League rooms kept:", kept_league)


if __name__ == "__main__":
    main()
