"""
Radio song lengths: intro and loop length (in frames) of every song the radio stations use.

Reads the station tables (src/data/radio_stations.h + radio_songs.h) for the MUS_* it lists, then each song's m4a track
data (sound/songs/midi/<song>.s, built from the MIDI by mid2agb; run `make` first). Track 1 carries the
tempo: the loop runs from the `<song>_1_B1:` marker (the MIDI's '[' loop start) to its GOTO (']').
m4a advances BPM/150 ticks a frame (24 ticks a beat), so frames = ticks * 150 / BPM, piecewise over TEMPO
changes. Songs without a loop (FINE) play once: their whole length counts as the intro.

Writes src/data/radio_song_lengths.h: #define RADIO_INTRO_MUS_X / RADIO_LOOP_MUS_X (frames).
usage: python3 dev_scripts/radio/song_lengths.py
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
STATIONS = [os.path.join(ROOT, "src", "data", f) for f in ("radio_stations.h", "radio_songs.h")]
OUT = os.path.join(ROOT, "src", "data", "radio_song_lengths.h")


def song_file(mus):
    name = mus.lower()
    for d in ("midi", ""):
        p = os.path.join(ROOT, "sound", "songs", d, name + ".s")
        if os.path.exists(p):
            return p
    return None


def parse(path, name):
    lines = open(path).read().split("\n")
    labels = {}
    for i, l in enumerate(lines):
        m = re.match(r"^(\w+):", l.strip())
        if m:
            labels[m.group(1)] = i
    start = labels.get(name + "_1")
    if start is None:
        raise ValueError("no track 1 in " + path)
    bpm = 120.0
    tbs = 1

    def run(i, until_pend, out):
        """Walk from line i; out = list of (ticks, bpm) segments; returns ('goto', label) / ('fine',) / ('pend',)."""
        nonlocal bpm
        while i < len(lines):
            l = lines[i].strip()
            m = re.match(r"^(\w+):", l)
            if m and m.group(1).endswith("_B1"):
                out.append(("B1", 0))
            if l.startswith(".byte"):
                for tok in [t.strip() for t in l[5:].split(",")]:
                    w = re.match(r"^W(\d\d)$", tok)
                    if w:
                        out.append((int(w.group(1)), bpm))
                tm = re.match(r"\.byte\s+TEMPO\s*,\s*(\d+)\*", l)
                if tm:
                    bpm = float(tm.group(1))
                if re.match(r"\.byte\s+GOTO\b", l):
                    tgt = lines[i + 1].strip().split()[-1]
                    return ("goto", tgt)
                if re.match(r"\.byte\s+FINE\b", l):
                    return ("fine",)
                if re.match(r"\.byte\s+PEND\b", l) and until_pend:
                    return ("pend",)
                if re.match(r"\.byte\s+PATT\b", l):
                    tgt = lines[i + 1].strip().split()[-1]
                    run(labels[tgt] + 1, True, out)
                    i += 1
            i += 1
        return ("fine",)

    segs = []
    end = run(start + 1, False, segs)
    intro = loop = 0.0
    in_loop = False
    for s in segs:
        if s[0] == "B1":
            in_loop = True
            continue
        ticks, b = s
        f = ticks * 150.0 / (b * tbs) if b else 0
        if in_loop and end[0] == "goto":
            loop += f
        else:
            intro += f
    return round(intro), round(loop)


def main():
    mus = sorted(set(re.findall(r"\b(MUS_[A-Z0-9_]+)\b", "".join(open(f).read() for f in STATIONS))))
    L = ["// GENERATED by dev_scripts/radio/song_lengths.py - do not edit.",
         "// Frames of each radio song's intro and loop (track 1, from the m4a song data)."]
    missing = []
    for m in mus:
        p = song_file(m)
        if p is None:
            missing.append(m)
            continue
        intro, loop = parse(p, os.path.splitext(os.path.basename(p))[0])
        L.append("#define RADIO_INTRO_%s %d" % (m, intro))
        L.append("#define RADIO_LOOP_%s %d" % (m, loop))
        print("%-28s intro %5d  loop %5d  (%.0fs a play)" % (m, intro, loop, (intro + 2 * loop) / 59.73))
    open(OUT, "w").write("\n".join(L) + "\n")
    if missing:
        sys.exit("no song data (run make first?): " + ", ".join(missing))


if __name__ == "__main__":
    main()
