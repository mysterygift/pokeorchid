    a("#define ODEX_E_NUM_CAP           %d" % M.E_NUM_CAP)
    a("#define ODEX_HW_W                70")
    a("#define ODEX_HW_CAP              %d" % M.HW_CAP)
    fx, fy, fw, fh = M.FOOT_WELL
    a("#define ODEX_FOOT_X              %d" % (fx + (fw - 16) // 2))
    a("#define ODEX_FOOT_Y              %d" % (fy + (fh - 16) // 2))
