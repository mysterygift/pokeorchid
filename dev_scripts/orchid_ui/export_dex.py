    a("#define ODEX_E_DAIS_STAGE_Y      %d" % (M.E_DAIS_C[1] + int(M.E_DAIS_IN * 0.55) + 3))
    a("#define ODEX_E_X                 %d" % M.E_X)
    a("#define ODEX_E_W                 %d" % M.E_W)
