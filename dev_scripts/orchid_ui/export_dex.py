    a("#define ODEX_S_Y0                %d" % SEARCH_Y0)
    a("#define ODEX_S_PITCH             %d" % SEARCH_PITCH)
    a("#define ODEX_S_BTN_X0            %d" % SEARCH_BTN_X[0])
