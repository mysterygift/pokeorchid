    a("#define ODEX_COUNT_X             %d" % M.COUNT_PILLS[0][0])
    a("#define ODEX_SEEN_Y              %d" % M.COUNT_PILLS[0][1])
    a("#define ODEX_OWN_Y               %d" % M.COUNT_PILLS[1][1])
    a("#define ODEX_COUNT_W             %d" % M.COUNT_W)
    a("#define ODEX_COUNT_CAP           %d" % M.COUNT_CAP)
