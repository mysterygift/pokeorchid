    a("#define ODEX_AREA_X0             %d" % ax0)
    a("#define ODEX_AREA_Y0             %d" % ay0)
    a("#define ODEX_AREA_X1             %d" % ax1)
    a("#define ODEX_AREA_Y1             %d" % ay1)
