def follower_sheet(sheet):
    """followers: base | δ by plain transfer_palette | δ as written (after FOLLOWER_FAMILY / FOLLOWER_OVERRIDES), 2x"""
    from PIL import ImageDraw, ImageFont
    cw, ch, cols = 3 * 68 + 8, 64 + 18, 6
    rows = (len(sheet) + cols - 1) // cols
    S = Image.new("RGB", (cols * cw + 10, rows * ch + 10), (236, 240, 236))
    dr = ImageDraw.Draw(S)
    try:
        f = ImageFont.truetype("/System/Library/Fonts/Supplemental/Arial Unicode.ttf", 12)
    except OSError:
        f = ImageFont.load_default()
    for n, (label, made) in enumerate(sheet):
        if "ow" not in made:
            continue
        x0, y0 = 5 + (n % cols) * cw, 5 + (n // cols) * ch
        pal0, pal1, png = made["ow"]
        im = Image.open(png).convert("P").crop((0, 0, 32, 32))
        for j, pal in enumerate((pal0, made["ow_old"], pal1)):
            o = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
            px, op = im.load(), o.load()
            for y in range(32):
                for x in range(32):
                    if px[x, y]:
                        op[x, y] = tuple(pal[px[x, y]]) + (255,)
            o = o.resize((64, 64), Image.NEAREST)
            S.paste(o, (x0 + j * 68, y0), o)
        dr.text((x0, y0 + 64), label, fill=(20, 20, 20), font=f)
    out = os.path.join(HERE, "shots")
    S.save(os.path.join(out, "followers_contact_sheet.png"))
    print("sheet:", os.path.join(out, "followers_contact_sheet.png"))


def contact_sheet(sheet):
    from PIL import ImageDraw, ImageFont
    k = 2
    cw, ch = 64 * k * 2 + 16 + 96, 64 * k + 22
    cols = 4
    rows = (len(sheet) + cols - 1) // cols
    S = Image.new("RGB", (cols * cw + 10, rows * ch + 10), (236, 240, 236))
    dr = ImageDraw.Draw(S)
    try:
        f = ImageFont.truetype("/System/Library/Fonts/Supplemental/Arial Unicode.ttf", 13)
    except OSError:
        f = ImageFont.load_default()
    for n, (label, made) in enumerate(sheet):
        x0, y0 = 5 + (n % cols) * cw, 5 + (n // cols) * ch
        v = made.get("delta_gba.pal") or made.get("delta.pal")
        im = Image.open(v[2]).convert("P")
        im = im.crop((0, 0, 64, 64))
        for j, pal in enumerate((v[0], v[1])):
            o = Image.new("RGBA", (64, 64), (0, 0, 0, 0))
            px, op = im.load(), o.load()
            for y in range(64):
                for x in range(64):
                    if px[x, y]:
                        op[x, y] = tuple(pal[px[x, y]]) + (255,)
            o = o.resize((64 * k, 64 * k), Image.NEAREST)
            S.paste(o, (x0 + j * (64 * k + 4), y0), o)
        if "ow" in made:
            pal0, pal1, png = made["ow"]
            im = Image.open(png).convert("P").crop((0, 0, 32, 32))
            for j, pal in enumerate((pal0, pal1)):
                o = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
                px, op = im.load(), o.load()
                for y in range(32):
                    for x in range(32):
                        if px[x, y]:
                            op[x, y] = tuple(pal[px[x, y]]) + (255,)
                o = o.resize((64, 64), Image.NEAREST)
                S.paste(o, (x0 + 2 * (64 * k + 4) + (j % 2) * 0, y0 + j * 60), o)
        dr.text((x0, y0 + 64 * k + 2), label, fill=(20, 20, 20), font=f)
    out = os.path.join(HERE, "shots")
    os.makedirs(out, exist_ok=True)
    S.save(os.path.join(out, "palettes_contact_sheet.png"))
    print("sheet:", os.path.join(out, "palettes_contact_sheet.png"))


