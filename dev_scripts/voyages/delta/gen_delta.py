def apply_override(pal, plan):
    new = list(pal)
    for idx, tgt in plan:
        rgb = TYPE_COLOUR[tgt] if isinstance(tgt, str) else tgt
        kind = "chrom" if sum(hsv(pal[i])[1] for i in idx) / len(idx) >= 0.16 else "grey"
        for i, c in recolour_family(pal, idx, rgb, kind).items():
            new[i] = c
    return new


