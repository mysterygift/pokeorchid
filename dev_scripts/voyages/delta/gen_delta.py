# ---------------------------------------------------------------- palettes
def read_pal(path):
    lines = open(path).read().split()
    n = int(lines[2])
    v = list(map(int, lines[3:3 + 3 * n]))
    pal = [tuple(v[i:i + 3]) for i in range(0, 3 * n, 3)]
    while len(pal) < 16:
        pal.append((0, 0, 0))
    return pal


def write_pal(path, pal):
    with open(path, "w", newline="\r\n") as f:
        f.write("JASC-PAL\n0100\n16\n")
        for c in pal:
            f.write("%d %d %d\n" % tuple(c))


def snap(c):
    c = [max(0, min(255, int(round(v)))) for v in c]
    return tuple((v & 0xF8) | (v >> 5) for v in c)


